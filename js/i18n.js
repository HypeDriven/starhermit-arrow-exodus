  var SUPPORTED = Object.keys(STRINGS);

  var lang = 'en-US';
  var dict = EN;

  /** Translate `key`, filling {placeholders} from vars; falls back to en-US, then `fallback`. */
  function t(key, vars, fallback) {
    var s = dict[key];
    if (s == null) s = EN[key];
    if (s == null) s = fallback != null ? fallback : key;
    if (vars) s = String(s).replace(/\{(\w+)\}/g, function (m, k) { return vars[k] != null ? vars[k] : m; });
    return s;
  }

  function apply() {
    if (typeof document === 'undefined') return;
    var nodes = document.querySelectorAll('[data-i18n]');
    for (var i = 0; i < nodes.length; i++) nodes[i].textContent = t(nodes[i].getAttribute('data-i18n'));
    var aria = document.querySelectorAll('[data-i18n-aria]');
    for (var j = 0; j < aria.length; j++) aria[j].setAttribute('aria-label', t(aria[j].getAttribute('data-i18n-aria')));
    document.documentElement.lang = lang;
  }

  function setLocale(next) {
    lang = STRINGS[next] ? next : 'en-US';
    dict = STRINGS[lang];
    if (typeof document === 'undefined') return;
    if (document.readyState !== 'loading') apply();
    document.dispatchEvent(new CustomEvent('ax-language', { detail: { lang: lang } }));
  }

